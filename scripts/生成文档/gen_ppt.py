def _font(run, size, bold=False, color=INK):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    run._r.get_or_add_rPr().set(qn('a:ea'), FONT) if False else None
    # eastAsia
    rPr = run._r.get_or_add_rPr()
    ea = rPr.find(qn('a:ea'))
    if ea is None:
        from pptx.oxml import parse_xml
        from pptx.oxml.ns import nsdecls
        ea = parse_xml('<a:ea %s typeface="%s"/>' % (nsdecls('a'), FONT))
        rPr.append(ea)


def box(slide, l, t, w, h):
    tb = slide.shapes.add_textbox(Inches(l), Inches(t), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    return tf


def slide(title, bullets, note='', kicker=None):
    s = prs.slides.add_slide(BLANK)
    # 顶部色条
    bar = s.shapes.add_shape(1, Inches(0), Inches(0), prs.slide_width, Inches(0.12))
    bar.fill.solid(); bar.fill.fore_color.rgb = BLUE; bar.line.fill.background()
    # 标题
    tf = box(s, 0.75, 0.45, 11.9, 1.0)
    if kicker:
        p0 = tf.paragraphs[0]
        _font(p0.add_run(), 13, color=BLUE)
        p0.runs[0].text = kicker
        p = tf.add_paragraph()
    else:
        p = tf.paragraphs[0]
    r = p.add_run(); r.text = title
    _font(r, 28, bold=True)
    # 要点
    tf2 = box(s, 0.95, 1.75, 11.6, 5.1)
    for i, b in enumerate(bullets):
        lvl = 0
        text = b
        if isinstance(b, tuple):
            text, lvl = b
        p = tf2.paragraphs[0] if i == 0 else tf2.add_paragraph()
        p.level = lvl
        r = p.add_run()
        r.text = ('· ' if lvl == 0 else '– ') + text
        _font(r, 18 if lvl == 0 else 15, color=INK if lvl == 0 else GRAY)
        p.space_after = Pt(10)
    if note:
        s.notes_slide.notes_text_frame.text = note
    return s


