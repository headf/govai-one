"""生成四份分人讲稿（通俗版，可直接照念）"""
import os
from docx import Document
from docx.shared import Pt, RGBColor
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

FONT = '微软雅黑'
INK = RGBColor(0x1F, 0x2D, 0x3D)
BLUE = RGBColor(0x2F, 0x6B, 0xFF)
GRAY = RGBColor(0x8A, 0x8A, 0x8A)
GREEN = RGBColor(0x1A, 0x7F, 0x4B)

OUTDIR = r'D:\Desktop\企业实训-智能政务系统\文档\答辩\讲稿-分人'
os.makedirs(OUTDIR, exist_ok=True)


def _font(run, size=11, bold=False, color=INK, italic=False):
    run.font.name = FONT
    run._element.get_or_add_rPr()
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color is not None:
        run.font.color.rgb = color


def build(name, role, blocks):
    doc = Document()
    st = doc.styles['Normal']
    st.font.name = FONT
    st.font.size = Pt(11)
    rpr = st.element.get_or_add_rPr()
    rf = rpr.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts'); rpr.append(rf)
    rf.set(qn('w:eastAsia'), FONT)
    st.paragraph_format.line_spacing = 1.5
    st.paragraph_format.space_after = Pt(4)

    # 封面标题
    p = doc.add_paragraph(); p.alignment = 1
    _font(p.add_run('GovAI One 智慧政务系统'), size=20, bold=True)
    p = doc.add_paragraph(); p.alignment = 1
    _font(p.add_run('答辩讲稿 · %s —— %s' % (name, role)), size=14, bold=True, color=BLUE)
    p.paragraph_format.space_after = Pt(4)
    p = doc.add_paragraph(); p.alignment = 1
    _font(p.add_run('（通俗版，可直接照着念；括号里是提示，不用念出来）'), size=10, color=GRAY)
    p.paragraph_format.space_after = Pt(14)

    for kind, text in blocks:
        if kind == 'h1':
            pp = doc.add_paragraph()
            _font(pp.add_run(text), size=15.5, bold=True, color=BLUE)
            pp.paragraph_format.space_before = Pt(14); pp.paragraph_format.space_after = Pt(6)
        elif kind == 'h2':
            pp = doc.add_paragraph()
            _font(pp.add_run(text), size=12.5, bold=True)
            pp.paragraph_format.space_before = Pt(9); pp.paragraph_format.space_after = Pt(3)
        elif kind == 't':
            pp = doc.add_paragraph(); _font(pp.add_run(text))
        elif kind == 'b':
            pp = doc.add_paragraph(); pp.paragraph_format.left_indent = Pt(16)
            _font(pp.add_run('· ' + text))
        elif kind == 'q':
            pp = doc.add_paragraph(); pp.paragraph_format.left_indent = Pt(12)
            _font(pp.add_run(text), size=10, color=GRAY, italic=True)
        elif kind == 'a':   # 答辩话术(绿)
            pp = doc.add_paragraph(); pp.paragraph_format.left_indent = Pt(16)
            _font(pp.add_run('答：' + text), color=GREEN, italic=True)
        elif kind == 'qq':  # 问题
            pp = doc.add_paragraph()
            _font(pp.add_run(text), size=12, bold=True)
            pp.paragraph_format.space_before = Pt(7); pp.paragraph_format.space_after = Pt(2)
        elif kind == 'page':
            doc.add_page_break()

    out = os.path.join(OUTDIR, '讲稿-%s-%s.docx' % (name, role))
    doc.save(out)
    return out


