st.paragraph_format.line_spacing = 1.45
st.paragraph_format.space_after = Pt(3)


def _f(run, size=11, bold=False, color=INK, italic=False):
    run.font.name = FONT
    run._element.get_or_add_rPr()
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color is not None:
        run.font.color.rgb = color


def H1(t):
    p = doc.add_paragraph(); _f(p.add_run(t), 17, True, BLUE)
    p.paragraph_format.space_before = Pt(18); p.paragraph_format.space_after = Pt(8)


def H2(t):
    p = doc.add_paragraph(); _f(p.add_run(t), 13, True)
    p.paragraph_format.space_before = Pt(11); p.paragraph_format.space_after = Pt(3)


def P(t):
    p = doc.add_paragraph(); _f(p.add_run(t)); return p


def label(lbl, text, color=INK):
    """【标签】内容"""
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Pt(10)
    _f(p.add_run(lbl + '：'), bold=True, color=color)
    _f(p.add_run(text))
    return p


def feat(name, how, tech, explain):
    """一个功能：名称 / 怎么实现 / 用什么技术 / 技术是什么"""
    p = doc.add_paragraph()
    _f(p.add_run('【' + name + '】'), 12, True, ORANGE)
    p.paragraph_format.space_before = Pt(9); p.paragraph_format.space_after = Pt(2)
    label('怎么实现的', how)
    label('用到什么技术', tech, color=BLUE)
    label('这些技术是什么', explain, color=GREEN)


def note(t):
    p = doc.add_paragraph(); p.paragraph_format.left_indent = Pt(12)
    _f(p.add_run(t), 10, color=GRAY, italic=True)


def table(rows, headers):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Light Grid Accent 1'
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ''
        _f(c.paragraphs[0].add_run(h), 10.5, True)
    for r in rows:
        cells = t.add_row().cells
        for i, v in enumerate(r):
            cells[i].text = ''
            _f(cells[i].paragraphs[0].add_run(v), 10)
    return t


