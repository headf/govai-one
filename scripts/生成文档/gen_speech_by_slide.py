P('答：不会。我们把结论和建议分开了：通过或不通过由规则引擎算出来，AI 只写核查要点；而且我们要求 AI"只能引用表单里真实存在的信息，不许编造"。审计日志里 AI 建议和人工决定也是分开记录的。', True)

P('Q3：为什么要拆成四个系统？', True)
P('答：因为四种用户的终端、权限、使用场景差别很大——老百姓用手机、企业用电脑、审批员用工作台、监管看大屏。拆开可以并行开发、独立部署，而且数据是隔离的，符合政务数据安全要求。', True)

P('Q4：审批推送给监管为什么用消息队列？', True)
P('答：因为这两个动作不需要"等"。审批员办完就该结束，不应该卡在那里等监管端收数据。用消息队列就像寄快递——交出去就行。而企业端提交申报是同步调用，因为要立刻拿到审批实例编号。', True)

P('Q5：如果两个人同时点"通过"怎么办？', True)
P('答：我们做了 CAS 并发控制——更新任务时带一个条件（只有状态还是"待处理"才允许更新成功），所以只有一个人能成功，另一个人会看到"任务已被他人办理"。', True)

P('Q6：四个端的界面风格是怎么统一的？', True)
P('答：我们抽了一套共享的"设计令牌"——主色、字号、圆角、状态色统一定义；电脑端用 Tailwind CSS 落地，手机端用同样数值的 CSS 变量（单位换算成 rpx）。所以四个端看起来是同一套设计语言。', True)

