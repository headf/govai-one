"""生成《GovAI One 逐页讲稿（对照 PPT）》"""
from docx import Document
from docx.shared import Pt, RGBColor
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

FONT = '微软雅黑'
INK = RGBColor(0x1F, 0x2D, 0x3D)
BLUE = RGBColor(0x2F, 0x6B, 0xFF)
GRAY = RGBColor(0x8A, 0x8A, 0x8A)
GREEN = RGBColor(0x1A, 0x7F, 0x4B)
ORANGE = RGBColor(0xB4, 0x5C, 0x00)

doc = Document()
st = doc.styles['Normal']
st.font.name = FONT
st.font.size = Pt(11)
rpr = st.element.get_or_add_rPr()
rf = rpr.find(qn('w:rFonts'))
if rf is None:
    rf = OxmlElement('w:rFonts'); rpr.append(rf)
rf.set(qn('w:eastAsia'), FONT)
st.paragraph_format.line_spacing = 1.5
st.paragraph_format.space_after = Pt(3)


def _f(run, size=11, bold=False, color=INK, italic=False):
    run.font.name = FONT
    run._element.get_or_add_rPr()
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color is not None:
        run.font.color.rgb = color


def title(t):
    p = doc.add_paragraph(); p.alignment = 1
    _f(p.add_run(t), 21, True)


def sub(t):
    p = doc.add_paragraph(); p.alignment = 1
    _f(p.add_run(t), 10.5, color=GRAY)
    p.paragraph_format.space_after = Pt(12)


def pagehead(t):
    p = doc.add_paragraph()
    _f(p.add_run(t), 15, True, BLUE)
    p.paragraph_format.space_before = Pt(16); p.paragraph_format.space_after = Pt(6)


def sec(t):
    """小节标签，如【照念】"""
    p = doc.add_paragraph()
    _f(p.add_run(t), 11.5, True, ORANGE)
    p.paragraph_format.space_before = Pt(6); p.paragraph_format.space_after = Pt(3)


def P(t, indent=False):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.left_indent = Pt(14)
    _f(p.add_run(t))
    return p


def SAY(t):
    """照念稿：略微缩进 + 绿色引导"""
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Pt(12)
    _f(p.add_run('「' ), color=GREEN)
    _f(p.add_run(t))
    _f(p.add_run('」'), color=GREEN)
    return p


def EN(term, full, meaning):
    """英文术语注解：词（全称，中文）→ 含义与意义"""
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Pt(14)
    _f(p.add_run('· ' + term), bold=True, color=BLUE)
    if full:
        _f(p.add_run('（' + full + '）'), color=GRAY)
    _f(p.add_run(' → ' + meaning), color=GREEN)
    return p


def TECH(name, what, why):
    """技术说明：干什么 / 为什么这么干"""
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Pt(14)
    _f(p.add_run('· ' + name + '：'), bold=True)
    _f(p.add_run(what))
    p2 = doc.add_paragraph()
    p2.paragraph_format.left_indent = Pt(30)
    _f(p2.add_run('为什么这么做：' + why), color=GRAY)
    return p


def tip(t):
    p = doc.add_paragraph(); p.paragraph_format.left_indent = Pt(12)
    _f(p.add_run(t), 10, color=GRAY, italic=True)


