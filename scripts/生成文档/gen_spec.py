H2('4.1 规则引擎与大模型的分工（核心设计）')
P('本系统的核心设计是"让 AI 帮忙，但不让 AI 拍板"，具体分工如下：')
TB(['层级', '做什么', '谁决定结论'], [
    ['规则引擎', '数值比较 / 文本匹配 / 日期判断 / 证照校验，支持 AND、OR 组合', '输出通过 / 未通过 / 转人工（确定性结论）'],
    ['AI 大模型', '生成核查要点与风险提示（仅作参考）', '不参与结论'],
    ['人工审批', '通过 / 驳回 / 退回补正，填写审批意见', '最终责任人与最终决定'],
])
P('落地方式：规则引擎的结论被注入 AI 意见的固定骨架（申报事项 / 申请人 / 规则校验结论 / 建议决定 / AI 核查要点），大模型只生成"核查要点"一段，且被提示词约束"只能引用表单中真实存在的信息、不得编造、不输出结论"。审计日志中 AI 建议与人工决定分开记录。')
P('规则全通过时，系统快进到办结出证岗等待人工复核（不自动办结）；出证人员仍需核对材料并确认后才真正办结。')

