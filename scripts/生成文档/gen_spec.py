# ==================== 8 使用说明 ====================
H1('8  使用说明')

H2('8.1 企业申报流程（企业端）')
P('登录企业端 → 进入办事大厅选择事项（或先用"智能办事规划"生成清单）→ 填写表单（企业信息自动带出，可上传营业执照由 OCR 回填）→ 上传材料（已有电子证照的材料自动免证办）→ 提交前系统自动预检 → 提交申请 → 在"我的申报"中查看进度 → 办结后在"证照空间"查看新签发的证照。')

H2('8.2 审批办理流程（审批端）')
P('登录审批端 → 在待办任务中查看本岗位待办 → 打开申报详情，核对申报表单、申报材料、规则引擎校验结果与 AI 核查要点 → 根据职责做出通过 / 驳回 / 退回补正的决定并填写审批意见 → 若为办结出证岗，核对材料后确认出证，系统自动回调企业端签发证照并通知群众端。')

H2('8.3 监管查看流程（监管端）')
P('登录监管端 → 数据大屏查看实时办件数据 → 在"双随机抽查"发起抽查（可按信用加权）→ 在"风险预警"查看与处置预警 → 在"企业信用"查看信用档案 → 在"差评整改"处置群众/企业上报的差评工单 → 在"审计追溯"输入审批实例号回溯全链路。')

H2('8.4 群众办事流程（群众端）')
P('手机号 + 验证码登录 → 在办事大厅浏览或搜索事项 → 查看事项详情与所需材料 → 在线填写并提交申报 → 在"进度查询"查看办理进展 → 有疑问可向 AI 办事助手提问 → 办结后收到站内信通知并可提交好差评。')

