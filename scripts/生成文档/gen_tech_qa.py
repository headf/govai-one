Q('Q16：免证办会不会导致漏交材料？')
A('不会。免证办是"用数据代替材料"，判断条件是：材料名含"营业执照/许可/资质"关键词，且企业名下确有对应类型的有效电子证照。只有"系统能核验到"的材料才免交，核验不到的必须上传。也就是说，免交的材料系统已经掌握了数据，不是不管。')

H2('四、信用与监管')
Q('Q17：信用等级怎么影响企业办事？')
A('目前是"失信受限"：申办补贴扶持类事项时，如果企业信用等级为 D 级，提交会被拦截并提示先做信用修复。反向的"守信激励"（如信用好可简化材料）是设计方向，当前未实现。')

Q('Q18：信用修复怎么保证真实？会不会随便修好？')
A('信用修复不是自动的，需要企业提交修复申请并附整改证明材料，由监管人员人工审核通过后才恢复分值，全过程留痕。也就是说，修复要走人工审核，不是系统自动放行。')

Q('Q19：监管端怎么发现审批环节有问题？')
A('有四个抓手：① 审批数据实时汇聚到大屏，办件量、办理时长、热点事项一目了然；② 风险预警规则（如"办理时长超阈值"）命中自动生成预警并走处置；③ 双随机抽查，随机抽件复核（按信用等级差异化抽）；④ 审计追溯，按实例号能回溯这一件的全部痕迹（谁办的、什么时候、是否被抽查过）。')

Q('Q20：双随机抽查怎么保证公平？')
A('"双随机"就是随机抽对象 + 随机派人，避免"想查谁就查谁"。我们在此基础上加了"信用差异化"：抽取时按信用等级加权，D 级企业最优先，其次 C、B、A——这样既保证随机性（不是人为指定），又把监管力量投向高风险对象。')

Q('Q21：差评整改的闭环是怎么跑通的？')
A('群众/企业给办结件打分，星级低于 3 星的差评会通过接口自动上报监管端，生成一条"差评整改工单"；监管人员在"差评整改"页面看到工单，填写整改措施完成处置，状态转为已处置。这就是"差评必整改"的闭环。上报失败只记日志，不影响评价本身提交。')

H2('五、AI 相关')
Q('Q22：AI 判断错了，谁负责？')
A('AI 不产生结论，所以不承担"判断"责任。系统的分工是：规则引擎给出可解释的结论、AI 只写核查要点、人工做最终决定并签字。审计日志中"AI 建议"与"人工决定"是分开记录的——出了问题能说清是哪个环节。')

Q('Q23：AI 会不会编造不存在的信息？')
A('会，这是大模型的固有风险（幻觉），所以我们做了三层约束：① 系统提示词明确要求"只能引用申报表单里真实存在的信息，不得虚构或联想"；② 大模型只写"核查要点"，即使写错也不影响结论（结论来自规则）；③ 输出后做文本清洗（去 Markdown、去表情、去多余符号）。另外还有失败降级——模型不可用时切本地知识库。')

Q('Q24：AI 的意见会和规则结论矛盾吗？')
A('不会。早期确实出现过（结论写"未通过"、AI 却在旁边说"材料齐全"），后来我们改成"固定骨架"：意见的格式写死，结论段由规则引擎直接注入，AI 只能填"核查要点"那一段——从机制上消除了矛盾的可能。')

Q('Q25：为什么不让 AI 直接给审批结论？')
A('因为大模型的输出不稳定、不可复现，而政务审批必须可解释、可追溯、责任到人。让 AI 直接判断，既不合规（无法说明依据），出了问题也说不清责任。所以我们的原则是"AI 辅助、人工决策"。')

H2('六、数据与安全')
Q('Q26：企业能看到别家企业的数据吗？')
A('不能。所有业务接口都会带当前登录企业的身份（从 token 里取企业 ID），查询时强制加上"企业 ID = 当前企业"的条件；申请数据、证照、材料都按企业隔离。跨端查询也是按 ID 精确取，不存在越权遍历。')

Q('Q27：四个库的数据怎么隔离？')
A('四个端各自一个独立 Schema（群众 / 审批 / 企业 / 监管），跨端**只能通过接口获取数据，不允许跨库直接查表**。这是政务数据"最小可见"原则的落地，也避免了服务之间的强耦合。')

Q('Q28：一条数据在四个端之间怎么保持一致？')
A('分情况：① 单库内用事务保证原子性（如审批实例状态与任务记录同时更新）；② 跨端用"回调 + 幂等"，回调失败不阻断主流程、重复通知只处理一次；③ 审批推监管走消息队列，队列持久化保证不丢。')

Q('Q29：审批端已办结，但企业端没收到回调，会怎样？')
A('回调做了容错：失败只记日志、不阻断审批（审批本身已经完成）。企业端的申报状态会暂时停留在"审批中"，需要人工核对或补偿。这是当前的边界——完整的方案是加"定时对账 + 重试补偿"，我们没有做到那一步。')

Q('Q30：文件存在哪？会不会丢？')
A('当前存在服务器本地磁盘（按日期分目录），通过静态资源映射对外访问；代码里预留了替换口，上线可换 MinIO / 对象存储。当前方案的局限是单机存储、没有副本，正式环境需要换成对象存储。')

H2('七、边界与异常')
Q('Q31：表单填了但材料没传，能提交吗？')
A('不能。提交时会校验材料齐全性：清单里每份材料要么已上传、要么由免证办自动核验，缺失会在服务端拦截并列出缺哪份——这个校验在后端做，前端绕过也无效。')

Q('Q32：事项被停用了，正在办的件怎么办？')
A('停用只是不再允许新申报（流程模板查询会过滤停用状态），已经在流程中的实例不受影响，继续按原流程办结。这正是"流程模板快照"的意义——已启动的实例不随配置变更而错乱。')

Q('Q33：数据库/消息队列挂了会怎样？')
A('数据库挂了系统不可用（这是单点）；消息队列挂了，审批端推送会失败，但审批主流程不受影响（推送是异步的），消息会在队列恢复后继续消费。Redis 挂了系统可降级运行（代码里做了降级）。')

H2('八、扩展性与整体')
Q('Q34：接入一个新事项，需要改代码吗？')
A('大部分不需要。事项信息、表单字段、流程模板、规则集、AI 提示词都是配置数据：新增事项只需在后台配置表单字段（前端动态渲染）、配流程模板（设计器编排节点）、配规则集（规则编辑器）。只有出现全新的业务形态（如全新的证照类型）才需要少量代码支持。')

Q('Q35：系统能支撑多少并发？')
A('如实说明：我们没有做压力测试，也没有实测并发指标。架构上是四个独立服务 + 消息队列削峰，理论上可以通过水平扩容提升；但当前是单机部署、单库实例，实际并发能力未验证——这是我们后续要补的测试项。')

Q('Q36：如果要做手机 App 怎么办？')
A('群众端已经是 uni-app 工程，它除了小程序和 H5，还能编译出 App（安卓/iOS），所以不需要重写。三个 PC 端如果要做 App，需要新开发或改造为响应式（当前是按桌面端设计的）。')

