H2('一、申报与受理')
Q('Q1：一件申报从提交到办结，要经过哪些环节？')
A('常规路径是四步：提交 → 受理初审 → 终审决定 → 办结出证。但有一个优化：如果规则引擎校验全部通过，系统会快进到最后的办结出证岗等待人工复核，跳过中间的受理和终审——因为"明显没问题"的件不必占用两个人工环节。')
B('两种路径最终都要人工办结，只是人工介入的环节数量不同。')

Q('Q2：为什么有的件能跳过受理和终审，这不算违规吗？')
A('这是"规则辅助、人工终审"的设计：规则负责挑出满足全部硬性条件的件（如面积达标、经营范围合规、证照有效），把它们直接送到出证岗；但出证岗仍要核对材料、人工确认才出证，最终签字权始终在人手里。规则不会自动办结。')

Q('Q3：群众和企业办同一件事，流程一样吗？')
A('流程模板是同一套（按事项编码配置），但入口和表单不同：群众端是手机小程序，企业端是 PC 门户；企业端多了"企业信息自动带出、OCR 回填、免证办、信用门禁"等能力。两者最终都提交到同一个审批端，走同一套流程。')

Q('Q4：企业提交后发现填错了，能改吗？')
A('分三种情况：① 还在草稿状态——可以随意改；② 已提交但审批未办结——不能直接改，需要审批端"退回补正"，企业再补充材料重新提交；③ 已办结——不能改。这个设计是为了保证审批过程的可追溯性（已提交的数据不能被单方面篡改）。')

Q('Q5：申报能撤回吗？')
A('群众端支持撤回未受理的申报。已受理进入审批流程的不能撤回（因为审批工作已经开始），只能等审批端处理或退回。')

Q('Q6：退回补正后能改几次？有没有限制？')
A('当前设计允许反复补正重提（每次退回都会清空历史退回意见、更新为最新意见）。实务上如果多次补正仍不合规，审批端可以直接"驳回"。')

H2('二、审批与流转')
Q('Q7：为什么规则全通过了还要人工办结？为什么不直接自动办结？')
A('这是本项目最重要的设计取舍。审批是要负法律责任的行政决定，必须有一个明确的责任人。规则只能保证"形式要件满足"（面积、经营范围、证照有效性等），但材料真实性、现场条件等无法通过规则判断。所以规则只做"快进到出证岗"，最终出证必须人工签字——出了问题能追溯到人。')

Q('Q8：三个岗位（受理初审 / 终审 / 办结出证）分别负责什么？')
A('受理初审岗：核对材料齐全性与形式合规（材料是否按要求提交、表单是否完整）；终审岗：对疑难件做实质审查并决定通过或驳回；办结出证岗：核准后签发证照（或触发作废），是最终出证环节。三个岗位"各看各的待办"，互不越权。')

Q('Q9：如果审批员长期不处理，件会一直卡着吗？')
A('当前没有实现超时自动提醒/自动流转（这是可以补的点）。现有的机制是：待办列表按岗位展示、待办数量统计，监管端可以配置"办理时长超过 N 天"的预警规则，触发后生成预警提醒——所以卡住是能被监管发现的，只是不会自动流转。')

Q('Q10：两个人同时审批同一件怎么办？')
