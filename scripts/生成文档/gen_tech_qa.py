Q('Q11：驳回和退回补正有什么区别？')
A('驳回是终止性的——申报状态置为已驳回，流程结束，企业需要重新申报；退回补正是可修复的——申报状态置为待补正，企业按退回意见补充材料后重新提交，流程继续。受理岗和终审岗可以驳回，办结岗不能驳回（终审已批准），只能退回终审复核或出证办结。')

H2('三、证照与材料')
Q('Q12：证照注销了，为什么还能再新办？')
A('可以新办，但要满足条件：新办时会校验"企业名下是否已有该类型的有效证照"——如果之前的证已经注销（不再是有效状态），就允许新办；如果已有一张有效的同类型证照，会拦截并提示走变更或延续。这样既允许"注销后重新办"，又防止"重复持证"。')

Q('Q13：延续和变更有什么区别？')
A('延续是"时间维度的更新"——原证快到期时续期换发，证照内容不变、只延长期限；变更是"内容维度的更新"——企业名称、地址、经营范围等发生了变化，需要换发新证。两者的共同点是旧证都会作废、签发新证；区别是作废原因不同（延续换发 / 变更换发），在证照历史里可以区分。')

Q('Q14：为什么会出现两张同类型的有效证照？（这是你们踩过的坑）')
A('这是我们在测试中发现的真实缺陷：早期"新办"环节没有做重复校验，导致企业可能重复办出两张同类证照。我们后来补了两道防护：① 提交时校验"已有同类型有效证照则不允许重复新办"；② 界面同类型多张有效证照时标注"同类型共 N 张"。这体现的是数据一致性在政务系统里的重要性。')

Q('Q15：材料造假怎么防？（重点，如实答）')
A('分三层防线，但要如实说明局限：')
B('上传时：校验文件类型（仅 JPG/PNG/PDF）与大小（≤10MB），挡住空文件、超大文件、格式不对的文件——服务端强制校验，前端限制可被绕过')
