"""生成《GovAI One 项目术语解释手册》"""
from docx import Document
from docx.shared import Pt, RGBColor
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

FONT = '微软雅黑'
INK = RGBColor(0x1F, 0x2D, 0x3D)
BLUE = RGBColor(0x2F, 0x6B, 0xFF)
GRAY = RGBColor(0x8A, 0x8A, 0x8A)
GREEN = RGBColor(0x1A, 0x7F, 0x4B)

doc = Document()
st = doc.styles['Normal']
st.font.name = FONT
st.font.size = Pt(11)
rpr = st.element.get_or_add_rPr()
rf = rpr.find(qn('w:rFonts'))
if rf is None:
    rf = OxmlElement('w:rFonts'); rpr.append(rf)
rf.set(qn('w:eastAsia'), FONT)
st.paragraph_format.line_spacing = 1.45
st.paragraph_format.space_after = Pt(3)


def _set(run, size=11, bold=False, color=INK, italic=False):
    run.font.name = FONT
    run._element.get_or_add_rPr()
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color is not None:
        run.font.color.rgb = color


def title(text):
    p = doc.add_paragraph(); p.alignment = 1
    _set(p.add_run(text), size=22, bold=True)
    p.paragraph_format.space_after = Pt(4)


def sub(text):
    p = doc.add_paragraph(); p.alignment = 1
    _set(p.add_run(text), size=10.5, color=GRAY)
    p.paragraph_format.space_after = Pt(14)


def h1(text):
    p = doc.add_paragraph()
    _set(p.add_run(text), size=16, bold=True, color=BLUE)
    p.paragraph_format.space_before = Pt(16); p.paragraph_format.space_after = Pt(6)


def term(name, plain, analogy=None, answer=None):
    """术语条目：名称 + 白话解释 + 打比方 + 答辩话术"""
    p = doc.add_paragraph()
    _set(p.add_run('● ' + name), size=12, bold=True)
    p.paragraph_format.space_before = Pt(8); p.paragraph_format.space_after = Pt(2)
    p2 = doc.add_paragraph(); p2.paragraph_format.left_indent = Pt(14)
    _set(p2.add_run('白话解释：' + plain))
    if analogy:
        p3 = doc.add_paragraph(); p3.paragraph_format.left_indent = Pt(14)
        _set(p3.add_run('打个比方：' + analogy), color=GRAY)
    if answer:
        p4 = doc.add_paragraph(); p4.paragraph_format.left_indent = Pt(14)
        _set(p4.add_run('答辩可以这么说：' + answer), color=GREEN, italic=True)


def note(text):
    p = doc.add_paragraph(); p.paragraph_format.left_indent = Pt(12)
    _set(p.add_run(text), size=10, color=GRAY, italic=True)


